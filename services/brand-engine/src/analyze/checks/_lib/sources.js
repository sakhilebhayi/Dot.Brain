// Parsed views over a Repo that several checks share, built once per run:
// templates, stylesheets (files and <style> blocks), user-facing copy units, the
// profile's rules and DESIGN.md front matter.
import { decodeEntities, parseTemplate, CTL, DYN, closest, hasAttr, attrValue } from './markup.js';
import { parseCss } from './css.js';
import { isShippedStyle, isShippedTemplate, kindOf, safeRel } from './repo.js';

// ---- templates -----------------------------------------------------------------------------------

function parsedTemplate(repo, rel) {
  const cache = repo.memo('parsedTemplates', () => new Map());
  if (!cache.has(rel)) {
    const source = repo.read(rel);
    const kind = kindOf(rel);
    cache.set(rel, source === null ? null : { rel, kind, source, ...parseTemplate(source, kind) });
  }
  return cache.get(rel);
}

/** The templates under analysis: all of them, or those under the --scope prefixes. */
export function templates(repo) {
  return repo.memo('templates', () => repo.list((r) => isShippedTemplate(r)).map((rel) => parsedTemplate(repo, rel)).filter(Boolean));
}

/** Every shipped template of the checkout, in scope or not: for reference scans ("is this view mounted?"), never for judging. */
export function allTemplates(repo) {
  return repo.memo('allTemplates', () => repo.listAll((r) => isShippedTemplate(r)).map((rel) => parsedTemplate(repo, rel)).filter(Boolean));
}

// ---- stylesheets ---------------------------------------------------------------------------------

const GENERATED = /tailwindcss v\d|^\/\*!|@generated|generated by|auto-generated/i;

export function stylesheets(repo) {
  return repo.memo('stylesheets', () => {
    const files = repo.list((rel) => isShippedStyle(rel));
    const hasSource = files.some((f) => !f.startsWith('public/'));
    const sheets = [];
    for (const rel of files) {
      if (hasSource && rel.startsWith('public/')) continue; // compiled output, not source
      const src = repo.read(rel);
      if (src === null) continue;
      if (GENERATED.test(src.slice(0, 400))) continue;
      sheets.push({ file: rel, inline: false, ...parseCss(src, { scss: /\.(?:scss|sass|less)$/i.test(rel) }) });
    }
    for (const t of templates(repo)) {
      for (const block of t.styleBlocks) {
        sheets.push({ file: t.rel, inline: true, ...parseCss(block.css, { lineOffset: block.line - 1 }) });
      }
    }
    return sheets;
  });
}

export const hasUi = (repo) => templates(repo).length > 0 || stylesheets(repo).length > 0;

// ---- profile -------------------------------------------------------------------------------------

const textOfItem = (x) => (typeof x === 'string' ? x : x && typeof x.text === 'string' ? x.text : null);
const listOf = (arr) => (Array.isArray(arr) ? arr.map(textOfItem).filter((s) => s !== null && s.trim() !== '') : []);

export function profileFacts(profile) {
  const lang = profile?.language ?? {};
  const policy = lang.claims_policy ?? {};
  return {
    present: Boolean(profile),
    id: profile?.id ?? null,
    bannedPhrases: listOf(lang.banned_phrases),
    forbidden: (Array.isArray(policy.forbidden) ? policy.forbidden : [])
      .filter((r) => r && typeof r.id === 'string' && typeof r.rule === 'string')
      .map((r) => ({ id: r.id, rule: r.rule })),
    evidenceRequired: listOf(policy.evidence_required),
    prohibited: listOf(profile?.visual_direction?.prohibited),
    sourceRefs: Array.isArray(profile?.visual_direction?.source_refs) ? profile.visual_direction.source_refs : [],
  };
}

// ---- evidence markers ----------------------------------------------------------------------------

/** A marker downgrades a finding only when the file it names exists inside the checkout. */
export function evidenceExists(repo, ref) {
  if (typeof ref !== 'string') return false;
  const path = ref.split('#')[0].split('?')[0];
  if (/^[a-z][a-z0-9+.-]*:/i.test(path)) return false; // a URL cannot be verified offline
  const rel = safeRel(path);
  return rel !== null && repo.exists(rel);
}

// ---- user-facing copy ----------------------------------------------------------------------------

const COPY_ATTRS = ['alt', 'title', 'placeholder', 'aria-label', 'aria-description', 'aria-placeholder', 'label'];
const SKIP_TEXT_PARENTS = new Set(['pre', 'code', 'kbd', 'samp', 'script', 'style', 'svg', 'math']);
const LANG_PATH = /(?:^|\/)(?:lang|locales?|i18n|translations?)\//i;

/** Remove markers so a phrase is matched on what a person would read. DYN becomes U+0001 (kept as a wall). */
const clean = (s) => decodeEntities(s.replaceAll(CTL, ' ')).replace(/[ \t]+/g, ' ');

function evidenceFor(tpl, el, line) {
  for (let p = el; p && p.type === 'el'; p = p.parent) {
    if (hasAttr(p, 'data-evidence')) return attrValue(p, 'data-evidence');
  }
  const m = tpl.evidenceMarkers.find((e) => e.line <= line && e.line >= line - 2);
  return m ? m.ref : null;
}

/**
 * Every user-facing string with its place: template text, a few attributes, and language
 * files. Text inside <pre>/<code> and developer comments is excluded.
 * A text unit keeps its line breaks: `line` is the line of its first character, and `lineInUnit`
 * maps an offset inside `text` to a file line.
 * @returns {Array<{file:string,line:number,text:string,source:'text'|'attr'|'lang',evidence:string|null,el:object|null}>}
 */
export function copyUnits(repo) {
  return repo.memo('copyUnits', () => {
    const units = [];
    for (const t of templates(repo)) {
      for (const node of t.texts) {
        const parent = node.parent;
        if (parent?.type === 'el' && (SKIP_TEXT_PARENTS.has(parent.tag) || closest(parent, (a) => SKIP_TEXT_PARENTS.has(a.tag)))) continue;
        const text = clean(node.text.slice(node.lead)).trimEnd();
        if (text.replaceAll(DYN, '').trim() === '') continue;
        const el = parent?.type === 'el' ? parent : null;
        units.push({ file: t.rel, line: node.line, text, source: 'text', evidence: evidenceFor(t, el, node.line), el });
      }
      for (const el of t.elements) {
        if (el.component) continue;
        for (const name of COPY_ATTRS) {
          const a = el.attrs.get(name);
          if (a && !a.dynamic && a.value.trim() !== '') {
            units.push({ file: t.rel, line: a.line, text: clean(a.value).trim(), source: 'attr', evidence: evidenceFor(t, el, a.line), el });
          }
        }
        if (el.tag === 'meta') {
          const nm = (attrValue(el, 'name') ?? attrValue(el, 'property') ?? '').toLowerCase();
          const c = el.attrs.get('content');
          if (c && !c.dynamic && /^(?:description|og:title|og:description|twitter:title|twitter:description)$/.test(nm) && c.value.trim() !== '') {
            units.push({ file: t.rel, line: c.line, text: clean(c.value).trim(), source: 'attr', evidence: evidenceFor(t, el, c.line), el });
          }
        }
        if (el.tag === 'input' && /^(?:submit|button|reset)$/i.test(attrValue(el, 'type') ?? '')) {
          const v = el.attrs.get('value');
          if (v && !v.dynamic && v.value.trim() !== '') units.push({ file: t.rel, line: v.line, text: clean(v.value).trim(), source: 'attr', evidence: evidenceFor(t, el, v.line), el });
        }
      }
    }
    for (const rel of repo.list((r, k) => LANG_PATH.test(r) && (k === 'php' || k === 'json') && !/\/(?:tests?|vendor)\//.test(r))) {
      const src = repo.read(rel);
      if (src === null) continue;
      if (rel.endsWith('.json')) {
        let data;
        try { data = JSON.parse(src); } catch { continue; }
        const strings = [];
        const walk = (v) => { if (typeof v === 'string') strings.push(v); else if (v && typeof v === 'object') for (const k of Object.keys(v)) walk(v[k]); };
        walk(data);
        const lines = src.split('\n');
        for (const s of strings) {
          if (s.trim() === '') continue;
          const needle = JSON.stringify(s).slice(1, -1);
          let line = lines.findIndex((l) => l.includes(needle)) + 1;
          if (line === 0) line = 1;
          units.push({ file: rel, line, text: s, source: 'lang', evidence: null, el: null });
        }
      } else {
        const lines = src.split('\n');
        lines.forEach((l, idx) => {
          const m = /=>\s*(['"])((?:\\.|(?!\1).)*)\1\s*,?\s*(?:\/\/.*)?$/.exec(l);
          if (!m || m[2].trim() === '') return;
          let ev = /evidence:\s*(\S+)/i.exec(l)?.[1] ?? (idx > 0 ? /^\s*(?:\/\/|#|\/\*)\s*evidence:\s*(\S+)/i.exec(lines[idx - 1])?.[1] : null) ?? null;
          if (ev) ev = ev.replace(/[)\].,;]+$/, '');
          units.push({ file: rel, line: idx + 1, text: m[2].replace(/\\(['"])/g, '$1'), source: 'lang', evidence: ev, el: null });
        });
      }
    }
    return units;
  });
}

// ---- DESIGN.md front matter ----------------------------------------------------------------------

/** Parse the YAML-ish front matter of a DESIGN.md (nested maps and scalars only). Returns {} when absent. */
export function frontMatter(text) {
  if (typeof text !== 'string' || !text.startsWith('---')) return {};
  const end = text.indexOf('\n---', 3);
  if (end === -1) return {};
  const lines = text.slice(3, end).split('\n');
  const root = {};
  const stack = [{ indent: -1, obj: root }];
  for (const raw of lines) {
    if (raw.trim() === '' || raw.trim().startsWith('#')) continue;
    const indent = raw.length - raw.trimStart().length;
    const m = /^([^:#]+?):\s*(.*)$/.exec(raw.trim());
    if (!m) continue;
    while (stack.length > 1 && stack[stack.length - 1].indent >= indent) stack.pop();
    const parent = stack[stack.length - 1].obj;
    const key = m[1].trim().replace(/^["']|["']$/g, '');
    let val = m[2].trim().replace(/\s+#.*$/, '');
    if (val === '') {
      const child = {};
      parent[key] = child;
      stack.push({ indent, obj: child });
    } else {
      val = val.replace(/^["']|["']$/g, '');
      parent[key] = val;
    }
  }
  return root;
}

export function designDoc(repo) {
  return repo.memo('design', () => {
    const rel = ['DESIGN.md', 'design.md', 'docs/DESIGN.md'].find((r) => repo.exists(r));
    if (!rel) return null;
    const text = repo.read(rel);
    return text === null ? null : { rel, text, front: frontMatter(text) };
  });
}

/** File line of an offset inside a unit's text. */
export const lineInUnit = (unit, offset) => unit.line + (unit.text.slice(0, offset).match(/\n/g)?.length ?? 0);
